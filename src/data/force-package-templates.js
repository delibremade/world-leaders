export const templatesFor=nid=>NATIONS[nid]?.play?Object.values(PACKAGE_TEMPLATES):[];
export function templateCandidates(nid,templateId){
  const t=PACKAGE_TEMPLATES[templateId];if(!NATIONS[nid]?.play||!t)return [];
  const units=deploymentIds(nid).map(id=>unitProfile(nid,id));
  return t.slots.map(s=>({...s,candidates:units.filter(u=>
    (!s.roles||s.roles.includes(u.role))&&(!s.services||s.services.includes(u.service))&&
    (s.carrierAir==null||s.carrierAir===u.carrierAir)&&(!s.stovl||u.stovl)&&
    (!s.carrierTypes||s.carrierTypes.includes(u.carrierType))).map(u=>u.id)}));
}
